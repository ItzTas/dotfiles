#!/usr/bin/env python3
"""Detect release automation in a repository, so /release doesn't step on it.

Checks the repo root for release tooling configs (semantic-release,
release-please, changesets, release-it, standard-version, cargo-release,
cargo-dist, goreleaser, knope, git-cliff, conventional-changelog,
python-semantic-release, commitizen) and CI that releases (GitHub workflows
named for releases, triggered by tags/releases or using release actions;
GitLab CI jobs with `release:` or tag rules).

Prints: {"root", "count", "found": [{"tool", "kind": "release|changelog|ci",
         "evidence": ["path[:line]"], "trigger"}]}
Exit: 0 nothing found, 1 automation found (stop and warn), 2 error.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
import tomllib
from collections.abc import Callable
from dataclasses import dataclass, field
from pathlib import Path
from typing import cast

FORBIDDEN = Path.home() / ".config" / "zsh" / "secrets"

TRIGGERS = {
    "semantic-release": "runs in CI on pushes to the release branch: it computes the version from the commits, tags and publishes; don't tag by hand",
    "release-please": "releases happen by merging the release PR that release-please opens/updates, not by tagging manually",
    "changesets": "add a changeset (`npx changeset`), then merge the 'Version Packages' PR (or run `changeset version` + `changeset publish`)",
    "release-it": "run `npx release-it` (it bumps, tags, writes the changelog and publishes)",
    "standard-version": "run `npx standard-version` (bump, changelog, tag), then `git push --follow-tags`",
    "conventional-changelog": "the changelog is generated by conventional-changelog (see the package.json scripts)",
    "cargo-release": "run `cargo release <level>` (bumps, tags, publishes per release.toml)",
    "cargo-dist": "pushing a version tag runs the release workflow generated by `dist`",
    "goreleaser": "pushing a tag runs goreleaser (usually in CI) to build and publish the release",
    "knope": "run `knope release` (or the CI workflow that calls it)",
    "git-cliff": "the changelog is generated by git-cliff with the repo's config (`git cliff`)",
    "python-semantic-release": "runs `semantic-release version`/`publish` (usually in CI) from the commits",
    "commitizen": "run `cz bump` (bumps the version, updates the changelog, tags)",
}

RELEASE_ACTIONS = re.compile(
    r"release-please-action|changesets/action|goreleaser/goreleaser-action|softprops/action-gh-release"
    + r"|ncipollo/release-action|actions/create-release|semantic-release|cargo-dist|\bdist (?:build|host)\b"
    + r"|taiki-e/(?:create-gh-release|upload-rust-binary)-action|pypa/gh-action-pypi-publish|npm publish|cargo publish"
)


@dataclass
class Finding:
    tool: str
    kind: str
    evidence: list[str] = field(default_factory=list)
    trigger: str = ""

    def as_dict(self) -> dict[str, object]:
        return {"tool": self.tool, "kind": self.kind, "evidence": self.evidence, "trigger": self.trigger or TRIGGERS.get(self.tool, "")}


def load_toml(path: Path) -> dict[str, object]:
    try:
        return tomllib.loads(path.read_text(encoding="utf-8"))
    except (OSError, tomllib.TOMLDecodeError):
        return {}


def load_json(path: Path) -> dict[str, object]:
    try:
        data = cast(object, json.loads(path.read_text(encoding="utf-8")))
    except (OSError, json.JSONDecodeError):
        return {}
    return cast(dict[str, object], data) if isinstance(data, dict) else {}


def dig(node: object, *keys: str) -> object:
    if not keys:
        return node
    if not isinstance(node, dict):
        return None
    return dig(cast(dict[str, object], node).get(keys[0]), *keys[1:])


def tracked(root: Path, *patterns: str) -> list[Path]:
    result = subprocess.run(["git", "-C", str(root), "ls-files", "--", *patterns], capture_output=True, text=True, check=False)
    if result.returncode != 0:
        return sorted(p for pattern in patterns for p in root.glob(pattern))
    return [root / line for line in result.stdout.splitlines() if line]


def existing(root: Path, names: list[str]) -> list[str]:
    return [name for name in names if (root / name).exists()]


def config_files(root: Path) -> list[Finding]:
    table: dict[str, tuple[str, list[str]]] = {
        "semantic-release": ("release", [".releaserc", *(f".releaserc.{e}" for e in ("json", "yaml", "yml", "js", "cjs", "mjs")),
                                         *(f"release.config.{e}" for e in ("js", "cjs", "mjs", "ts"))]),
        "release-please": ("release", ["release-please-config.json", ".release-please-manifest.json"]),
        "changesets": ("release", [".changeset"]),
        "release-it": ("release", [*(f".release-it.{e}" for e in ("json", "js", "cjs", "ts", "yaml", "yml", "toml"))]),
        "standard-version": ("release", [".versionrc", ".versionrc.json", ".versionrc.js", ".versionrc.cjs"]),
        "cargo-release": ("release", ["release.toml"]),
        "cargo-dist": ("release", ["dist-workspace.toml", "dist.toml"]),
        "goreleaser": ("release", [".goreleaser.yml", ".goreleaser.yaml", "goreleaser.yml", "goreleaser.yaml"]),
        "knope": ("release", ["knope.toml"]),
        "git-cliff": ("changelog", ["cliff.toml", ".cliff.toml"]),
        "commitizen": ("release", [".cz.toml", "cz.toml", ".cz.json", "cz.json", ".cz.yaml", "cz.yaml"]),
    }
    findings: list[Finding] = []
    for tool, (kind, names) in table.items():
        hits = existing(root, names)
        if hits:
            findings.append(Finding(tool, kind, hits))
    return findings


def package_json(root: Path) -> list[Finding]:
    pkg = load_json(root / "package.json")
    if not pkg:
        return []
    deps: set[str] = set()
    for section in ("dependencies", "devDependencies"):
        value = pkg.get(section)
        if isinstance(value, dict):
            deps.update(cast(dict[str, object], value))
    checks: dict[str, tuple[str, Callable[[], bool]]] = {
        "semantic-release": ("release", lambda: "release" in pkg or "semantic-release" in deps),
        "release-it": ("release", lambda: "release-it" in pkg or "release-it" in deps),
        "changesets": ("release", lambda: "@changesets/cli" in deps),
        "standard-version": ("release", lambda: "standard-version" in pkg or "standard-version" in deps),
        "conventional-changelog": ("changelog", lambda: any(d.startswith("conventional-changelog") for d in deps)),
    }
    return [Finding(tool, kind, ["package.json"]) for tool, (kind, check) in checks.items() if check()]


def toml_tables(root: Path) -> list[Finding]:
    cargo = load_toml(root / "Cargo.toml")
    pyproject = load_toml(root / "pyproject.toml")
    checks: list[tuple[str, str, str, object]] = [
        ("cargo-release", "release", "Cargo.toml [*.metadata.release]", dig(cargo, "package", "metadata", "release") or dig(cargo, "workspace", "metadata", "release")),
        ("cargo-dist", "release", "Cargo.toml [workspace.metadata.dist]", dig(cargo, "workspace", "metadata", "dist") or dig(cargo, "package", "metadata", "dist")),
        ("git-cliff", "changelog", "Cargo.toml [*.metadata.git-cliff]", dig(cargo, "workspace", "metadata", "git-cliff") or dig(cargo, "package", "metadata", "git-cliff")),
        ("git-cliff", "changelog", "pyproject.toml [tool.git-cliff]", dig(pyproject, "tool", "git-cliff")),
        ("python-semantic-release", "release", "pyproject.toml [tool.semantic_release]", dig(pyproject, "tool", "semantic_release")),
        ("commitizen", "release", "pyproject.toml [tool.commitizen]", dig(pyproject, "tool", "commitizen")),
    ]
    return [Finding(tool, kind, [evidence]) for tool, kind, evidence, hit in checks if hit is not None and hit is not False]


def tag_patterns(lines: list[str], start: int) -> list[str]:
    """Collects the patterns listed under a `tags:` key (inline list or `- item` lines)."""
    inline = lines[start].split(":", 1)[1].strip()
    if inline:
        return [p.strip(" '\"") for p in inline.strip("[]").split(",") if p.strip()]
    patterns: list[str] = []
    for line in lines[start + 1 :]:
        item = re.match(r"^\s*-\s*(.+)$", line)
        if not item:
            break
        patterns.append(item.group(1).strip(" '\""))
    return patterns


def workflow_signals(rel: str, lines: list[str]) -> tuple[list[str], list[str]]:
    """Scans one workflow: tag/release triggers under `on:`, release jobs and actions."""
    evidence: list[str] = []
    hints: list[str] = []
    section = ""
    for i, line in enumerate(lines):
        if top := re.match(r"^[\"']?([A-Za-z_][\w-]*)[\"']?\s*:(.*)$", line):
            section = top.group(1)
            if section in ("on", "true") and re.search(r"\brelease\b", top.group(2)):
                evidence.append(f"{rel}:{i + 1}")
                hints.append("runs when a GitHub release is created/published")
            continue
        if section in ("on", "true") and re.match(r"^\s+tags\s*:", line):
            evidence.append(f"{rel}:{i + 1}")
            hints.append(f"runs when a tag is pushed ({', '.join(tag_patterns(lines, i)) or 'any tag'})")
        elif section in ("on", "true") and re.match(r"^\s+release\s*:", line):
            evidence.append(f"{rel}:{i + 1}")
            hints.append("runs when a GitHub release is created/published")
        elif section == "jobs" and re.match(r"^\s{1,4}[\w-]*release[\w-]*\s*:\s*$", line):
            evidence.append(f"{rel}:{i + 1}")
            hints.append(f"has a `{line.strip().rstrip(':')}` job")
        elif match := RELEASE_ACTIONS.search(line):
            evidence.append(f"{rel}:{i + 1}")
            hints.append(f"uses {match.group(0)}")
    return evidence, hints


def github_workflows(root: Path) -> list[Finding]:
    findings: list[Finding] = []
    for path in tracked(root, ".github/workflows/*.yml", ".github/workflows/*.yaml"):
        rel = path.relative_to(root).as_posix()
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        evidence, hints = workflow_signals(rel, lines)
        if not evidence and "release" not in path.name.lower():
            continue
        if not evidence:
            evidence, hints = [rel], ["workflow named for releases: check its `on:` trigger"]
        findings.append(Finding(f"github-actions:{path.name}", "ci", evidence[:6], "; ".join(dict.fromkeys(hints))))
    return findings


def gitlab_ci(root: Path) -> list[Finding]:
    findings: list[Finding] = []
    for path in tracked(root, ".gitlab-ci.yml", "*.gitlab-ci.yml", ".gitlab/**/*.yml", ".gitlab/**/*.yaml"):
        rel = path.relative_to(root).as_posix()
        try:
            lines = path.read_text(encoding="utf-8").splitlines()
        except OSError:
            continue
        evidence: list[str] = []
        hints: list[str] = []
        signals = {
            r"^\s+release\s*:\s*$": "a job uses the `release:` keyword to create the GitLab release",
            r"release-cli|glab release create": "a job creates the GitLab release",
            r"\$CI_COMMIT_TAG|\bonly\s*:\s*\[?\s*tags|^\s*-\s*tags\s*$": "jobs run when a tag is pushed",
            r"semantic-release|goreleaser|npm publish|cargo publish|twine upload|uv publish": "a job publishes the release",
        }
        for i, line in enumerate(lines):
            for pattern, hint in signals.items():
                if re.search(pattern, line):
                    evidence.append(f"{rel}:{i + 1}")
                    hints.append(hint)
        if evidence:
            findings.append(Finding(f"gitlab-ci:{rel}", "ci", evidence[:6], "; ".join(dict.fromkeys(hints))))
    return findings


def repo_root(start: Path) -> Path:
    result = subprocess.run(["git", "-C", str(start), "rev-parse", "--show-toplevel"], capture_output=True, text=True, check=False)
    return Path(result.stdout.strip()) if result.returncode == 0 else start


class Args(argparse.Namespace):
    C: str = "."


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    _ = parser.add_argument("-C", default=".", help="repository directory (default: cwd)")
    args = parser.parse_args(namespace=Args())
    root = repo_root(Path(args.C).resolve())
    if root == FORBIDDEN or FORBIDDEN in root.parents:
        print("detect-automation: refusing to scan that directory", file=sys.stderr)
        return 2
    if not root.is_dir():
        print(f"detect-automation: not a directory: {root}", file=sys.stderr)
        return 2
    merged: dict[str, Finding] = {}
    for finding in [*config_files(root), *package_json(root), *toml_tables(root), *github_workflows(root), *gitlab_ci(root)]:
        current = merged.setdefault(finding.tool, Finding(finding.tool, finding.kind, [], finding.trigger))
        current.evidence.extend(e for e in finding.evidence if e not in current.evidence)
    found = [f.as_dict() for f in merged.values()]
    json.dump({"root": str(root), "count": len(found), "found": found}, sys.stdout, separators=(",", ":"))
    _ = sys.stdout.write("\n")
    return 1 if found else 0


if __name__ == "__main__":
    sys.exit(main())
